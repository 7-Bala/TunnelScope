#!/usr/bin/env python3
"""T-156: how good is a traffic-classifier recipe, measured three ways, with the gap between them printed.

  1. random windows (LEAKY: windows of one session land on both sides; reported only to show the inflation)
  2. grouped by session (no session on both sides; all families pooled)
  3. leave one FAMILY out (train on every other family, predict a family never seen): the honest test of
     "traffic from generators it has never met", and the number to quote

Session-level answer = argmax of the mean window probability, over sessions with at least MIN_WINDOWS windows.
Macro-F1 is over the classes present in what is being scored.

  .venv/bin/python build/models/generalisation_report.py [--version v1] [--out build/models/GENERALISATION.md]
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import f1_score
from sklearn.model_selection import GroupKFold, StratifiedKFold

sys.path.insert(0, str(Path(__file__).resolve().parent))
import corpus  # noqa: E402
import featurize  # noqa: E402

SEED = 156


def shipped_rf(**kw):
    return RandomForestClassifier(n_estimators=200, random_state=0, n_jobs=-1, min_samples_leaf=2, **kw)


def macro(y, p):
    labs = sorted(set(y))
    return float(f1_score(y, p, labels=labs, average="macro", zero_division=0))


def stack(sessions, wins, idx):
    X = np.vstack([wins[i] for i in idx]) if idx else np.zeros((0, 1))
    y = np.concatenate([[sessions[i].label] * len(wins[i]) for i in idx]) if idx else np.array([])
    return X, y


def session_predict(model, sessions, wins, idx):
    ys, ps = [], []
    for i in idx:
        P = model.predict_proba(wins[i])
        ys.append(sessions[i].label)
        ps.append(str(model.classes_[int(P.mean(axis=0).argmax())]))
    return ys, ps


def report(version="v1", families=None, make_model=shipped_rf):
    ss = corpus.load(families)
    wins = featurize.windows(ss, version)
    ok = [i for i, w in enumerate(wins) if len(w) >= featurize.MIN_WINDOWS]
    fams = [f for f in corpus.FAMILIES if any(ss[i].family == f for i in ok)]
    R = {"version": version, "families": {}, "insufficient": dict(Counter(ss[i].family for i, w in enumerate(wins) if len(w) < featurize.MIN_WINDOWS))}
    for f in fams:
        sub = [i for i in ok if ss[i].family == f]
        R["families"][f] = {"sessions": len(sub), "windows": int(sum(len(wins[i]) for i in sub)), "classes": dict(Counter(ss[i].label for i in sub))}
    # 1. leaky: random windows
    X, y = stack(ss, wins, ok)
    pred = np.empty(len(y), dtype=object)
    for tr, te in StratifiedKFold(5, shuffle=True, random_state=SEED).split(X, y):
        pred[te] = make_model().fit(X[tr], y[tr]).predict(X[te])
    R["leaky_random_windows"] = {"window_macro_f1": round(macro(y, pred.astype(str)), 4)}
    # 2. grouped by session (all families pooled)
    groups = np.arange(len(ok))
    ys, ps, wy, wp = [], [], [], []
    for tr, te in GroupKFold(5).split(groups, groups, groups):
        Xt, yt = stack(ss, wins, [ok[j] for j in tr])
        m = make_model().fit(Xt, yt)
        a, b = session_predict(m, ss, wins, [ok[j] for j in te]); ys += a; ps += b
        Xe, ye = stack(ss, wins, [ok[j] for j in te])
        wy += ye.tolist(); wp += m.predict(Xe).tolist()          # window level, to compare like with like
    R["grouped_by_session"] = {"session_macro_f1": round(macro(ys, ps), 4), "window_macro_f1": round(macro(wy, wp), 4),
                               "sessions": len(ys)}
    # 3. leave one family out
    lofo = {}
    for f in fams:
        tr = [i for i in ok if ss[i].family != f]
        te = [i for i in ok if ss[i].family == f]
        Xt, yt = stack(ss, wins, tr)
        m = make_model().fit(Xt, yt)
        a, b = session_predict(m, ss, wins, te)
        lofo[f] = {"session_macro_f1": round(macro(a, b), 4), "accuracy": round(float(np.mean([u == v for u, v in zip(a, b)])), 4),
                   "sessions": len(te), "per_class_f1": {c: round(float(v), 3) for c, v in zip(sorted(set(a)), f1_score(a, b, labels=sorted(set(a)), average=None, zero_division=0))}}
    R["leave_one_family_out"] = lofo
    vals = [v["session_macro_f1"] for v in lofo.values()]
    R["lofo_mean_macro_f1"] = round(float(np.mean(vals)), 4)
    R["lofo_worst_macro_f1"] = round(float(np.min(vals)), 4)
    return R


def to_markdown(R):
    L = [f"# Traffic classifier: how well does it generalise? (feature version `{R['version']}`)", "",
         "Generated by `build/models/generalisation_report.py` (T-156). Session-level answers; macro-F1 over the classes present.", "",
         "| Split | What it tests | Macro-F1 |", "|---|---|---|",
         f"| random windows (**leaky**) | nothing honest: windows of one session on both sides | {R['leaky_random_windows']['window_macro_f1']} (windows) |",
         f"| grouped by session | new sessions from generators it has already seen | {R['grouped_by_session']['session_macro_f1']} |",
         f"| **leave one family out (mean)** | **traffic from generators it has never seen** | **{R['lofo_mean_macro_f1']}** (worst {R['lofo_worst_macro_f1']}) |", "",
         f"Window level, leaky random split {R['leaky_random_windows']['window_macro_f1']} vs grouped by session "
         f"{R['grouped_by_session']['window_macro_f1']}: the leak buys "
         f"{R['leaky_random_windows']['window_macro_f1'] - R['grouped_by_session']['window_macro_f1']:+.3f}. Session level, seen "
         f"generators {R['grouped_by_session']['session_macro_f1']} vs never-seen families {R['lofo_mean_macro_f1']}: "
         f"{R['lofo_mean_macro_f1'] - R['grouped_by_session']['session_macro_f1']:+.3f}.", "",
         "## Leave one family out", "", "| Held-out family | Sessions | Macro-F1 | Accuracy | Per class |", "|---|---|---|---|---|"]
    for f, v in R["leave_one_family_out"].items():
        L.append(f"| {f} | {v['sessions']} | {v['session_macro_f1']} | {v['accuracy']} | {', '.join(f'{c} {s}' for c, s in v['per_class_f1'].items())} |")
    L += ["", "## Data", "", "| Family | Sessions (>= 3 windows) | Windows | Classes |", "|---|---|---|---|"]
    for f, v in R["families"].items():
        L.append(f"| {f} | {v['sessions']} | {v['windows']} | {', '.join(f'{c} {n}' for c, n in sorted(v['classes'].items()))} |")
    if R["insufficient"]:
        L += ["", f"Sessions with fewer than 3 windows (never scored): {R['insufficient']}"]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--version", default="v1")
    ap.add_argument("--out", default=str(Path(__file__).resolve().parent / "GENERALISATION.md"))
    a = ap.parse_args()
    R = report(a.version)
    Path(a.out).write_text(to_markdown(R))
    Path(a.out).with_suffix(".json").write_text(json.dumps(R, indent=1))
    print(to_markdown(R))
