def _lsw(change, why, before, after, verification="docs-only", also=None, verify=None):
    """One Libreswan template. `before`/`after` are the weak and fixed `key=value` lines of the connection; the lab harness builds the
    weak connection from `before` and applies `after` as written."""
    lines = [f"{k}={v}" for k, v in after.items() if v is not None]
    gone = [k for k, v in after.items() if v is None]                  # a None value means: remove that line
    return {"change": change, "why": why, "example_before": dict(before), "example_after": dict(after),
            "commands": [f"in {LSW_CONF}, set: " + "  ".join(lines)] + ([f"remove the line(s): {', '.join(gone)}"] if gone else [])
                        + ([also] if also else []) + [LSW_RELOAD],
            "config_diff": "\n".join([f"- {k}={v}" for k, v in before.items()] + [f"+ {k}={v}" for k, v in after.items() if v is not None]
                                      + [f"- {k}" for k in gone]),
            "verify": verify or "ipsec status   (the established connection lists the new algorithms)",
            "verification": verification}


def _ros(change, why, edits, verification="docs-only"):
    """One RouterOS template. `edits`: list of (menu, label, {setting: value}); `<label>` is the item's name on the device. A label that
    contains `=` is a finder expression as it is (policies have no name: `ipsec-protocols=ah`)."""
    cmds, diff = [], []
    for menu, label, settings in edits:
        find = label if "=" in label else f"name=<{label}>"
        cmds.append(f"{menu} set [ find {find} ] " + " ".join(f"{k}={v}" for k, v in settings.items()))
        diff += [f"+ {menu} [{find}] {k}={v}" for k, v in settings.items()]
    verify = "; ".join(f"{m} print detail where " + (f"{next(iter(st))}={st[next(iter(st))]}" if "=" in lb else f"name=<{lb}>") for m, lb, st in edits)
    return {"change": change, "why": why, "commands": cmds, "config_diff": "\n".join(diff), "verify": verify,
            "verification": verification, "edits": [{"menu": m, "label": lb, "set": dict(s)} for m, lb, s in edits]}


