def vendor_plan(rule_id: str, vendor: str, observed=None, detailed: bool = False) -> dict | None:
    """The plan for `rule_id` on `vendor`, or None when TunnelScope has no plan for the rule at all."""
    from .plan import REMEDIATION
    base = REMEDIATION.get(rule_id)
    if not base:
        return None
    t = TEMPLATES[vendor].get(rule_id)
    reason = None
    if t is None:
        reason = _PATCH_REASON if rule_id in PATCH_RULES else NO_TEMPLATE[vendor].get(rule_id, "no template written for this rule on this vendor yet")
    res = {"rule_id": str(rule_id), "vendor": vendor, "vendor_label": VENDOR_LABEL[vendor], "observed": observed,
           "template": t is not None, "auto_applicable": False, "automated_fix_available": False,
           "change": t["change"] if t else base["change"], "commands": list(t["commands"]) if t else [],
           "verification": t["verification"] if t else None, "source": SOURCES[vendor]}
    if t is None:
        res["reason"] = reason
    if detailed:
        res["config_diff"] = t["config_diff"] if t else ""
        res["config_diff_is_example"] = True
        res["verify"] = t["verify"] if t else ""
        res["why"] = t["why"] if t else ""
        res["problem_analysis"] = base.get("problem_analysis", "")
        res["cryptographic_risk"] = base.get("cryptographic_risk", "")
        res["scope"] = ("Advice only: nothing is applied by TunnelScope on this vendor. The dry-run, snapshot and rollback pipeline "
                        "exists for the strongSwan lab only.")
    return res
